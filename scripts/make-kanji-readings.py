#!/usr/bin/env python3
"""Builds the kanji reading list used to put each furigana reading over its own kanji.

Usage: scripts/make-kanji-readings.py path/to/kanjidic2.xml.gz

Download kanjidic2.xml.gz from https://www.edrdg.org/kanjidic/kanjidic2.xml.gz. Keeps the jōyō and jinmeiyō
kanji (KANJIDIC grades 1–10) with their on readings (in hiragana) and kun readings (okurigana dropped), and writes:
  QuickActions/kanji-readings.txt          read by furigana.js in the Quick Actions
  Sources/AmadareCore/KanjiReadings.swift  the same list, embedded in the app
"""
import gzip
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = [
    "Kanji readings for furigana: one kanji per line, then its readings in hiragana, space-separated.",
    "Derived from KANJIDIC2 by the Electronic Dictionary Research and Development Group (EDRDG),",
    "https://www.edrdg.org/edrdg/licence.html, used under CC BY-SA 4.0; this list is under the same licence.",
    "Generated by scripts/make-kanji-readings.py; don't edit by hand.",
]


def hiragana(s):
    return "".join(chr(ord(c) - 0x60) if 0x30A1 <= ord(c) <= 0x30F6 else c for c in s)


def main(path):
    with gzip.open(path) as f:
        root = ET.parse(f).getroot()
    lines = []
    for ch in root.iter("character"):
        grade = ch.findtext("misc/grade")
        if not grade or not 1 <= int(grade) <= 10:
            continue
        readings = []
        for r in ch.iter("reading"):
            kind = r.get("r_type")
            if kind not in ("ja_on", "ja_kun"):
                continue
            text = hiragana(r.text.split(".")[0].strip("-"))
            if text and text not in readings:
                readings.append(text)
        if readings:
            lines.append(ch.findtext("literal") + " " + " ".join(readings))
    lines.sort()

    (ROOT / "QuickActions/kanji-readings.txt").write_text(
        "".join("# " + h + "\n" for h in HEADER) + "\n".join(lines) + "\n", encoding="utf-8")
    swift = (
        "".join("// " + h + "\n" for h in HEADER)
        + "\nenum KanjiReadings {\n"
        + "    /// Readings of each jōyō and jinmeiyō kanji, in hiragana.\n"
        + "    static let table: [Character: [String]] = {\n"
        + "        var table: [Character: [String]] = [:]\n"
        + "        for line in data.split(separator: \"\\n\") {\n"
        + "            let parts = line.split(separator: \" \").map(String.init)\n"
        + "            if let kanji = parts.first?.first { table[kanji] = Array(parts.dropFirst()) }\n"
        + "        }\n"
        + "        return table\n"
        + "    }()\n\n"
        + "    private static let data = \"\"\"\n"
        + "\n".join(lines)
        + "\n\"\"\"\n}\n"
    )
    (ROOT / "Sources/AmadareCore/KanjiReadings.swift").write_text(swift, encoding="utf-8")
    print(f"{len(lines)} kanji")


if __name__ == "__main__":
    main(sys.argv[1])
